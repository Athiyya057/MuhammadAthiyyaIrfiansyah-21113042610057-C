# String equality and inequality
name = "Athiyya"

print(name == "Athiyya")
print(name != "Athiyya")

print(name.lower() == "athiyya")
print(name.lower() == "Athiyya")

number = 18

print(number == 18)
print(number != 18)
print(number > 10)
print(number < 10)
print(number >= 18)
print(number <= 10)

print(number > 10 and number < 20)
print(number < 10 and number > 5)

print(number > 10 or number < 5)
print(number < 10 or number > 20)

fruits = ["apple", "banana", "orange"]

print("apple" in fruits)
print("grape" in fruits)

print("grape" not in fruits)
print("apple" not in fruits)